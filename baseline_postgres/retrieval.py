"""Small, safe PostgreSQL retrieval functions for the structured MIMIC data."""

from __future__ import annotations

import os
from datetime import datetime
from typing import Any

import psycopg
from psycopg.rows import dict_row


class PostgresRetriever:
    """Read-only retrieval facade over the MIMIC-IV PostgreSQL schemas.

    Connection settings come from standard PG* environment variables. The
    facade intentionally exposes allow-listed query templates instead of
    accepting SQL generated by an LLM.
    """

    def __init__(self, conninfo: str | None = None):
        self.conninfo = conninfo or os.environ.get("DATABASE_URL")

    def _connect(self):
        return psycopg.connect(self.conninfo, row_factory=dict_row) if self.conninfo else psycopg.connect(row_factory=dict_row)

    @staticmethod
    def _rows(cur) -> list[dict[str, Any]]:
        return [dict(row) for row in cur.fetchall()]

    def patient_context(self, subject_id: int) -> dict[str, Any]:
        """Return demographics plus all known hospital and ICU encounters."""
        
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute("""
                SELECT subject_id, gender, anchor_age, anchor_year,
                       anchor_year_group, dod
                FROM mimiciv_hosp.patients
                WHERE subject_id = %s
            """, (subject_id,))
            patient = cur.fetchone()
            cur.execute("""
                SELECT hadm_id, admittime, dischtime, admission_type,
                       admission_location, discharge_location, hospital_expire_flag
                FROM mimiciv_hosp.admissions
                WHERE subject_id = %s
                ORDER BY admittime
            """, (subject_id,))
            admissions = self._rows(cur)
            cur.execute("""
                SELECT stay_id, hadm_id, intime, outtime, first_careunit, last_careunit
                FROM mimiciv_icu.icustays
                WHERE subject_id = %s
                ORDER BY intime
            """, (subject_id,))
            icu_stays = self._rows(cur)
        return {"patient": dict(patient) if patient else None,
                "admissions": admissions, "icu_stays": icu_stays}

    def admissions(self, subject_id: int, limit: int = 100) -> list[dict[str, Any]]:
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute("""
                SELECT subject_id, hadm_id, admittime, dischtime, deathtime,
                       admission_type, admission_location, discharge_location,
                       insurance, language, race, hospital_expire_flag
                FROM mimiciv_hosp.admissions
                WHERE subject_id = %s
                ORDER BY admittime
                LIMIT %s
            """, (subject_id, limit))
            return self._rows(cur)

    def labs(self, subject_id: int, hadm_id: int | None = None,
             start: datetime | None = None, end: datetime | None = None,
             itemids: list[int] | None = None, limit: int = 500) -> list[dict[str, Any]]:
        clauses = ["l.subject_id = %s"]
        params: list[Any] = [subject_id]
        if hadm_id is not None:
            clauses.append("l.hadm_id = %s"); params.append(hadm_id)
        if start is not None:
            clauses.append("l.charttime >= %s"); params.append(start)
        if end is not None:
            clauses.append("l.charttime < %s"); params.append(end)
        if itemids:
            clauses.append("l.itemid = ANY(%s)"); params.append(itemids)
        params.append(limit)
        query = f"""
            SELECT l.labevent_id, l.subject_id, l.hadm_id, l.charttime,
                   l.itemid, d.label, d.fluid, l.value, l.valuenum,
                   l.valueuom, l.ref_range_lower, l.ref_range_upper, l.flag
            FROM mimiciv_hosp.labevents l
            LEFT JOIN mimiciv_hosp.d_labitems d ON d.itemid = l.itemid
            WHERE {' AND '.join(clauses)}
            ORDER BY l.charttime NULLS LAST, l.labevent_id
            LIMIT %s
        """
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute(query, params)
            return self._rows(cur)

    def diagnoses(self, subject_id: int, hadm_id: int | None = None,
                  limit: int = 200) -> list[dict[str, Any]]:
        where = ["d.subject_id = %s"]; params: list[Any] = [subject_id]
        if hadm_id is not None:
            where.append("d.hadm_id = %s"); params.append(hadm_id)
        params.append(limit)
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute(f"""
                SELECT d.subject_id, d.hadm_id, d.seq_num, d.icd_code,
                       d.icd_version, ref.long_title
                FROM mimiciv_hosp.diagnoses_icd d
                LEFT JOIN mimiciv_hosp.d_icd_diagnoses ref
                  ON ref.icd_code = d.icd_code AND ref.icd_version = d.icd_version
                WHERE {' AND '.join(where)}
                ORDER BY d.hadm_id, d.seq_num
                LIMIT %s
            """, params)
            return self._rows(cur)

    def medications(self, subject_id: int, hadm_id: int | None = None,
                    limit: int = 500) -> list[dict[str, Any]]:
        where = ["subject_id = %s"]; params: list[Any] = [subject_id]
        if hadm_id is not None:
            where.append("hadm_id = %s"); params.append(hadm_id)
        params.append(limit)
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute(f"""
                SELECT subject_id, hadm_id, pharmacy_id, starttime, stoptime,
                       drug, drug_type, dose_val_rx, dose_unit_rx, route
                FROM mimiciv_hosp.prescriptions
                WHERE {' AND '.join(where)}
                ORDER BY starttime NULLS LAST
                LIMIT %s
            """, params)
            return self._rows(cur)

    def procedures(self, subject_id: int, hadm_id: int | None = None,
                   limit: int = 200) -> list[dict[str, Any]]:
        where = ["p.subject_id = %s"]; params: list[Any] = [subject_id]
        if hadm_id is not None:
            where.append("p.hadm_id = %s"); params.append(hadm_id)
        params.append(limit)
        with self._connect() as conn, conn.cursor() as cur:
            cur.execute(f"""
                SELECT p.subject_id, p.hadm_id, p.seq_num, p.chartdate,
                       p.icd_code, p.icd_version, ref.long_title
                FROM mimiciv_hosp.procedures_icd p
                LEFT JOIN mimiciv_hosp.d_icd_procedures ref
                  ON ref.icd_code = p.icd_code AND ref.icd_version = p.icd_version
                WHERE {' AND '.join(where)}
                ORDER BY p.chartdate NULLS LAST, p.seq_num
                LIMIT %s
            """, params)
            return self._rows(cur)

